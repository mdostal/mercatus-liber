/**
 * The real, currently-published event names this repo's subsystems emit on
 * @mercatus-liber/core's EventBus, re-verified by grepping every real
 * `events.publish(...)` call site across `packages/` (not assumed/copied
 * from a doc) as of this package's creation:
 *   - packages/payments/src/{stripe,sandbox}-adapter.ts
 *   - packages/catalog/src/service.ts
 *   - packages/promotions/src/service.ts
 *   - packages/cart/src/service.ts
 *   - packages/checkout-orders/src/service.ts
 *   - packages/reviews/src/service.ts
 *
 * `EventBus.subscribe` (packages/core/src/event-bus.ts) takes an exact event
 * name, not a wildcard/glob -- there is no "subscribe to everything" primitive
 * on the bus itself. WebhookDeliveryService (service.ts in this package)
 * therefore has to subscribe individually to a known list of event names
 * rather than intercepting publish() generically; this constant is that
 * list, exported so a deployer whose own app has added more real events can
 * pass a wider list into `createWebhookDeliveryService`'s `eventTypes`
 * option instead of being stuck with only what this repo ships today. See
 * this epic's design-discussion.md §4 for the honest disclosure of this as
 * a real limitation, not a hidden one.
 */
export const KNOWN_EVENT_TYPES = [
  "payments.payment.succeeded",
  "payments.payment.failed",
  "catalog.product.created",
  "catalog.product.updated",
  "catalog.product.archived",
  "catalog.sku.created",
  "catalog.attribute.updated",
  "catalog.attribute.removed",
  "promotions.redeemed",
  "cart.item.added",
  "cart.item.removed",
  "cart.item.updated",
  "cart.cleared",
  "checkout.order.paid",
  "checkout.order.placed",
  "reviews.review.submitted",
  "reviews.review.published",
] as const;

export type KnownEventType = (typeof KNOWN_EVENT_TYPES)[number];

/**
 * A registered external subscription: one target URL plus which real event
 * type(s) it wants delivered to it, and the per-subscription secret used to
 * HMAC-sign every delivery to that URL (see signer.ts). `eventTypes` is a
 * plain `string[]`, not narrowed to `KnownEventType[]` -- mirrors
 * @mercatus-liber/fulfillment's own `FulfillmentProviderKey` precedent
 * (deliberately not a closed union so a deployer's own custom event names
 * are a real, supported option, not a type error) -- see KNOWN_EVENT_TYPES's
 * own doc comment above for why the matching bus subscription has to be told
 * about those names explicitly too.
 */
export interface WebhookSubscription {
  id: string;
  url: string;
  eventTypes: string[];
  /** Per-subscription HMAC-SHA256 key. Generated by createWebhookSubscription when not supplied; never logged, never included in a delivery-log entry's body. */
  secret: string;
  active: boolean;
  createdAt: string;
}

/** Input to createWebhookSubscription -- id/createdAt are always service-assigned; secret is optional (generated when omitted); active defaults to true. */
export type NewWebhookSubscriptionInput = Omit<WebhookSubscription, "id" | "createdAt" | "active" | "secret"> & {
  secret?: string;
  active?: boolean;
};

export type WebhookDeliveryStatus = "success" | "failed";

/**
 * One real delivery attempt -- the audit trail a consumer needs to debug a
 * missed webhook, per this epic's own requirement. One row per HTTP attempt
 * (not one row per event): a 3-attempt retry sequence for the same event
 * produces 3 WebhookDeliveryLogEntry rows sharing the same `deliveryId`, so
 * "what was sent, when, and what came back" is visible for every individual
 * attempt, not just the final outcome.
 */
export interface WebhookDeliveryLogEntry {
  id: string;
  /** Shared across every attempt for the same event delivery to the same subscription -- correlates a retry sequence. */
  deliveryId: string;
  subscriptionId: string;
  eventType: string;
  attemptNumber: number;
  /** The exact raw JSON string body sent on the wire (what was signed, byte for byte) -- not a re-serialization. */
  requestBody: string;
  /** HTTP status code received, or null when the attempt never got a response at all (network error/timeout). */
  responseStatus: number | null;
  status: WebhookDeliveryStatus;
  /** Set only when status is "failed" -- the network error message, or a plain description of the non-2xx status received. */
  error: string | null;
  attemptedAt: string;
}

/**
 * The persistence-adapter contract for subscriptions, mirroring this repo's
 * existing shape exactly: @mercatus-liber/advertising's CampaignRepository
 * (get/list/save) and @mercatus-liber/inventory's InventoryAdapter are the
 * two precedents named by this epic's own brief. get/list/save here is the
 * CampaignRepository shape (list over save+filter, not a bespoke query
 * method); delete is added because, unlike a Campaign, a subscription a
 * consumer no longer wants has to be genuinely removable, not just archived.
 */
export interface WebhookSubscriptionStore {
  get(id: string): Promise<WebhookSubscription | null>;
  list(filter?: { eventType?: string; active?: boolean }): Promise<WebhookSubscription[]>;
  save(subscription: WebhookSubscription): Promise<void>;
  delete(id: string): Promise<void>;
}

/** The persistence-adapter contract for the delivery audit trail -- append-only (no update/delete: a delivery attempt that already happened is a historical fact). */
export interface WebhookDeliveryLogStore {
  record(entry: WebhookDeliveryLogEntry): Promise<void>;
  listForSubscription(subscriptionId: string): Promise<WebhookDeliveryLogEntry[]>;
}
